class V58BacktestEngine:
    """
    V58 回测引擎
    
    【核心功能】
    1. 行业先行选股
    2. 因子评分排序
    3. 三级防御体系止损止盈
    4. 波动率适配头寸管理
    5. 交易审计与洗售检测
    """
    
    def __init__(self, initial_capital: float = V58_INITIAL_CAPITAL):
        self.initial_capital = initial_capital
        self.capital = initial_capital
        self.positions: Dict[str, V58Position] = {}
        self.trades: List[V58Trade] = []
        self.trade_audit: List[V58TradeAudit] = []
        self.wash_sale_records: List[V58WashSaleRecord] = []
        self.blacklist: Dict[str, V58BlacklistRecord] = {}
        self.weekly_trades: Dict[int, V58WeeklyTradeCounter] = {}
        self.market_regime: Optional[V58MarketRegime] = None
        self.drawdown_state: Optional[V58DrawdownState] = None
        
        self.factor_engine = V58FactorEngine()
        self.risk_manager = V58RiskManager()
        self.industry_loader = V58IndustryLoader()
        
        self.total_trades = 0
        self.daily_pnl: Dict[str, float] = {}
        self.equity_curve: List[Tuple[str, float]] = []
    
    def get_week_number(self, trade_date: str) -> Tuple[int, int]:
        """获取周数"""
        try:
            dt = datetime.strptime(trade_date, "%Y-%m-%d")
            return dt.isocalendar()[1], dt.isocalendar()[0]
        except Exception:
            return 1, 2026
    
    def check_weekly_trade_limit(self, trade_date: str) -> bool:
        """检查周交易限制"""
        week_num, year = self.get_week_number(trade_date)
        key = (year, week_num)
        
        if key not in self.weekly_trades:
            self.weekly_trades[key] = V58WeeklyTradeCounter(week_number=week_num, year=year)
        
        counter = self.weekly_trades[key]
        return counter.trade_count < V58_WEEKLY_TRADE_LIMIT
    
    def increment_weekly_trade_count(self, trade_date: str):
        """增加周交易计数"""
        week_num, year = self.get_week_number(trade_date)
        key = (year, week_num)
        
        if key not in self.weekly_trades:
            self.weekly_trades[key] = V58WeeklyTradeCounter(week_number=week_num, year=year)
        
        self.weekly_trades[key].trade_count += 1
    
    def check_global_trade_limit(self) -> bool:
        """检查全局交易限制"""
        return self.total_trades < V58_GLOBAL_TRADE_LIMIT
    
    def check_wash_sale(self, symbol: str, trade_date: str) -> bool:
        """检查洗售交易"""
        if symbol not in self.blacklist:
            return False
        
        record = self.blacklist[symbol]
        try:
            sell_date = datetime.strptime(record.sell_date, "%Y-%m-%d")
            buy_date = datetime.strptime(trade_date, "%Y-%m-%d")
            days_between = (buy_date - sell_date).days
            
            record.days_remaining = max(0, V58_WASH_SALE_WINDOW - days_between)
            
            if days_between <= V58_WASH_SALE_WINDOW:
                return True
        except Exception:
            pass
        
        return False
    
    def add_to_blacklist(self, symbol: str, sell_date: str, reason: str):
        """将股票加入黑名单"""
        try:
            sell_dt = datetime.strptime(sell_date, "%Y-%m-%d")
            expiry_dt = sell_dt + timedelta(days=V58_WASH_SALE_WINDOW)
            
            self.blacklist[symbol] = V58BlacklistRecord(
                symbol=symbol,
                sell_date=sell_date,
                stop_reason=reason,
                blacklist_expiry_day=expiry_dt.strftime("%Y-%m-%d"),
                days_remaining=V58_WASH_SALE_WINDOW
            )
        except Exception:
            pass
    
    def calculate_commission(self, amount: float, is_buy: bool) -> Tuple[float, float, float, float]:
        """计算手续费"""
        commission = max(amount * V58_COMMISSION_RATE, V58_MIN_COMMISSION)
        slippage = amount * (V58_SLIPPAGE_BUY if is_buy else V58_SLIPPAGE_SELL)
        stamp_duty = amount * V58_STAMP_DUTY if not is_buy else 0.0
        transfer_fee = amount * V58_TRANSFER_FEE
        
        return commission, slippage, stamp_duty, transfer_fee
    
    def execute_buy(self, symbol: str, trade_date: str, signal_date: str,
                    price: float, shares: int, signal_score: float,
                    signal_rank: int, composite_score: float,
                    atr: float, industry_name: str = "") -> Optional[V58Trade]:
        """执行买入"""
        if shares <= 0 or self.capital <= 0:
            return None
        
        amount = price * shares
        commission, slippage, stamp_duty, transfer_fee = self.calculate_commission(amount, True)
        total_cost = amount + commission + slippage + transfer_fee
        
        if total_cost > self.capital:
            available = self.capital - commission - slippage - transfer_fee
            if available > price:
                shares = int(available / price)
                shares = (shares // 100) * 100
                if shares <= 0:
                    return None
                amount = price * shares
                total_cost = amount + commission + slippage + transfer_fee
        
        execution_price = price * (1 + V58_SLIPPAGE_BUY)
        
        trade = V58Trade(
            trade_date=trade_date,
            symbol=symbol,
            side='BUY',
            shares=shares,
            price=price,
            amount=amount,
            commission=commission,
            slippage=slippage,
            stamp_duty=stamp_duty,
            transfer_fee=transfer_fee,
            total_cost=total_cost,
            reason="因子选股信号",
            execution_price=execution_price,
            signal_date=signal_date,
            t_plus_1=True
        )
        
        self.trades.append(trade)
        self.capital -= total_cost
        
        position = V58Position(
            symbol=symbol,
            shares=shares,
            avg_cost=execution_price,
            buy_price=execution_price,
            buy_date=trade_date,
            signal_date=signal_date,
            trade_date=trade_date,
            signal_score=signal_score,
            signal_rank=signal_rank,
            composite_score=composite_score,
            current_price=execution_price,
            market_value=execution_price * shares,
            atr_at_entry=atr,
            industry_name=industry_name,
            entry_composite_score=composite_score
        )
        
        position.hard_stop_price = execution_price * (1 - V58_HARD_STOP_LOSS_RATIO)
        position.peak_price = execution_price
        
        self.positions[symbol] = position
        self.increment_weekly_trade_count(trade_date)
        self.total_trades += 1
        
        return trade
    
    def execute_sell(self, symbol: str, trade_date: str, price: float,
                     reason: str, position: Optional[V58Position] = None) -> Optional[V58Trade]:
        """执行卖出"""
        if position is None:
            position = self.positions.get(symbol)
        
        if position is None or position.shares <= 0:
            return None
        
        shares = position.shares
        amount = price * shares
        commission, slippage, stamp_duty, transfer_fee = self.calculate_commission(amount, False)
        total_cost = commission + slippage + stamp_duty + transfer_fee
        net_proceeds = amount - total_cost
        
        execution_price = price * (1 - V58_SLIPPAGE_SELL)
        
        trade = V58Trade(
            trade_date=trade_date,
            symbol=symbol,
            side='SELL',
            shares=shares,
            price=price,
            amount=amount,
            commission=commission,
            slippage=slippage,
            stamp_duty=stamp_duty,
            transfer_fee=transfer_fee,
            total_cost=total_cost,
            reason=reason,
            execution_price=execution_price,
            signal_date=position.signal_date,
            holding_days=position.holding_days,
            trigger_price=position.stop_trigger_price if hasattr(position, 'stop_trigger_price') else 0,
            next_open_price=position.stop_next_open if hasattr(position, 'stop_next_open') else 0
        )
        
        self.trades.append(trade)
        self.capital += net_proceeds
        
        buy_price = position.avg_cost
        gross_pnl = (execution_price - buy_price) * shares
        net_pnl = gross_pnl - total_cost
        
        audit = V58TradeAudit(
            symbol=symbol,
            buy_date=position.buy_date,
            sell_date=trade_date,
            buy_price=buy_price,
            sell_price=execution_price,
            shares=shares,
            gross_pnl=gross_pnl,
            total_fees=total_cost,
            net_pnl=net_pnl,
            holding_days=position.holding_days,
            is_profitable=net_pnl > 0,
            sell_reason=reason,
            entry_signal=position.signal_score,
            signal_rank=position.signal_rank,
            atr_at_entry=position.atr_at_entry,
            hard_stop_price=position.hard_stop_price,
            hard_stop_triggered=position.hard_stop_triggered,
            breakeven_active=position.breakeven_active,
            trailing_profit_active=position.trailing_profit_active,
            trailing_profit_triggered=position.trailing_profit_triggered,
            ma20_exit_triggered=position.ma20_exit_triggered,
            time_stop_triggered=position.time_stop_triggered,
            tiered_profit_triggered=position.tiered_profit_triggered.copy(),
            peak_price=position.peak_price,
            exit_profit_ratio=(execution_price - buy_price) / buy_price if buy_price > 0 else 0,
            position_tier=position.position_tier,
            volume_shrunk_at_entry=position.volume_shrunk_at_entry,
            rs_score=position.rs_score,
            rs_rank=position.rs_rank,
            trigger_price=trade.trigger_price,
            next_open_price=trade.next_open_price,
            execution_price=execution_price,
            slippage_applied=V58_SLIPPAGE_SELL
        )
        
        self.trade_audit.append(audit)
        
        del self.positions[symbol]
        
        self.add_to_blacklist(symbol, trade_date, reason)
        
        return trade
    
    def update_positions(self, trade_date: str, price_data: pl.DataFrame):
        """更新持仓数据"""
        for symbol, position in list(self.positions.items()):
            try:
                stock_data = price_data.filter(pl.col('symbol') == symbol)
                if stock_data.is_empty():
                    continue
                
                current_price = stock_data['close'][0]
                current_atr = stock_data['atr_20'][0] if 'atr_20' in stock_data.columns else 0
                current_ma20 = stock_data['ma20'][0] if 'ma20' in stock_data.columns else 0
                
                position.current_price = current_price
                position.market_value = current_price * position.shares
                position.unrealized_pnl = (current_price - position.avg_cost) * position.shares
                position.current_profit_ratio = (current_price - position.avg_cost) / position.avg_cost if position.avg_cost > 0 else 0
                
                try:
                    buy_date = datetime.strptime(position.buy_date, "%Y-%m-%d")
                    current = datetime.strptime(trade_date, "%Y-%m-%d")
                    position.holding_days = (current - buy_date).days
                except Exception:
                    pass
                
                if current_price > position.peak_price:
                    position.peak_price = current_price
                    position.peak_profit = (current_price - position.avg_cost) / position.avg_cost if position.avg_cost > 0 else 0
                
                self.risk_manager.update_position_stops(position, current_price, current_atr, current_ma20)
                
            except Exception as e:
                logger.error(f"Error updating position {symbol}: {e}")
    
    def check_exits(self, trade_date: str, price_data: pl.DataFrame) -> List[V58Trade]:
        """检查并执行离场"""
        exit_trades = []
        
        for symbol, position in list(self.positions.items()):
            try:
                stock_data = price_data.filter(pl.col('symbol') == symbol)
                if stock_data.is_empty():
                    continue
                
                current_price = stock_data['close'][0]
                current_atr = stock_data['atr_20'][0] if 'atr_20' in stock_data.columns else 0
                current_ma20 = stock_data['ma20'][0] if 'ma20' in stock_data.columns else current_price
                
                triggered, reason = self.risk_manager.check_all_exits(
                    position, current_price, current_atr, current_ma20, trade_date
                )
                
                if triggered:
                    trade = self.execute_sell(symbol, trade_date, current_price, reason, position)
                    if trade:
                        exit_trades.append(trade)
                        logger.info(f"V58 Exit: {symbol} - {reason}")
                
            except Exception as e:
                logger.error(f"Error checking exit for {symbol}: {e}")
        
        return exit_trades
    
    def select_stocks(self, trade_date: str, factor_data: pl.DataFrame,
                      industry_data: Optional[pl.DataFrame] = None) -> List[Dict[str, Any]]:
        """选股逻辑 - 简化过滤逻辑"""
        try:
            current_df = factor_data.filter(pl.col('trade_date') == trade_date)
            if current_df.is_empty():
                logger.debug(f"No data for trade_date: {trade_date}")
                return []
            
            # 行业先行过滤
            if V58_INDUSTRY_FILTER_ENABLED:
                current_df, industry_stats = v58_industry_filter(
                    current_df, industry_data, self.industry_loader,
                    trade_date, V58_INDUSTRY_TOP_N
                )
                logger.debug(f"After industry filter: {current_df.height} stocks")
            
            # 只保留核心过滤条件：entry_allowed（基于 composite_rank 的 Top N）
            # 其他过滤器作为参考，不强制过滤
            entry_allowed_df = current_df.filter(
                pl.col('entry_allowed') == True
            )
            
            if entry_allowed_df.is_empty():
                # 如果仍然为空，尝试放宽到 Top 100
                entry_allowed_df = current_df.filter(
                    pl.col('composite_rank') <= max(V58_ENTRY_TOP_N, 100)
                )
                logger.debug(f"Relaxed to Top 100: {entry_allowed_df.height} stocks")
            
            if entry_allowed_df.is_empty():
                logger.debug(f"No entry_allowed stocks for {trade_date}")
                return []
            
            # 按综合评分排序
            entry_allowed_df = entry_allowed_df.sort('composite_score', descending=True)
            
            # 调试日志
            logger.debug(f"Entry allowed: {entry_allowed_df.height} stocks, top score: {entry_allowed_df['composite_score'][0] if not entry_allowed_df.is_empty() else 0:.4f}")
            
            candidates = []
            for row in entry_allowed_df.iter_rows(named=True):
                symbol = row['symbol']
                
                # 跳过已持仓
                if symbol in self.positions:
                    continue
                
                # 跳过洗售黑名单
                if self.check_wash_sale(symbol, trade_date):
                    continue
                
                # 检查周交易限制
                if not self.check_weekly_trade_limit(trade_date):
                    continue
                
                # 检查全局交易限制
                if not self.check_global_trade_limit():
                    continue
                
                candidates.append({
                    'symbol': symbol,
                    'composite_score': row.get('composite_score', 0),
                    'signal_rank': row.get('composite_rank', 9999),
                    'atr': row.get('atr_20', 0),
                    'rs_rank': row.get('rs_rank', 9999),
                    'rs_score': row.get('rs_strength', 0),
                    'industry_name': row.get('industry_name', ''),
                    'volume_breakout': row.get('volume_breakout', False),
                    'ma20_breakout': row.get('ma20_breakout', False)
                })
                
                if len(candidates) >= V58_MAX_POSITIONS:
                    break
            
            if candidates:
                logger.info(f"Selected {len(candidates)} candidates for {trade_date}: {[c['symbol'] for c in candidates[:3]]}")
            
            return candidates
            
        except Exception as e:
            logger.error(f"V58 select_stocks failed: {e}")
            logger.error(traceback.format_exc())
            return []
    
    def run_backtest(self, factor_data: pl.DataFrame, price_data: pl.DataFrame,
                     industry_data: Optional[pl.DataFrame] = None,
                     start_date: str = "", end_date: str = "") -> Dict[str, Any]:
        """运行回测"""
        try:
            trade_dates = sorted(factor_data['trade_date'].unique().to_list())
            
            for trade_date in trade_dates:
                daily_pnl = 0.0
                
                price_df = price_data.filter(pl.col('trade_date') == trade_date)
                
                exit_trades = self.check_exits(trade_date, price_df)
                for trade in exit_trades:
                    # net_proceeds = amount - total_cost
                    net_proceeds = trade.amount - trade.total_cost
                    daily_pnl += net_proceeds
                
                self.update_positions(trade_date, price_df)
                
                candidates = self.select_stocks(trade_date, factor_data, industry_data)
                
                for candidate in candidates:
                    stock_price = price_df.filter(pl.col('symbol') == candidate['symbol'])
                    if stock_price.is_empty():
                        continue
                    
                    price = stock_price['close'][0]
                    atr = candidate.get('atr') or stock_price['atr_20'][0] if 'atr_20' in stock_price.columns else 0.02 * price
                    
                    shares = self.risk_manager.calculate_position_size(
                        self.capital, price, atr or 0.02 * price, 0.02
                    )
                    
                    if shares > 0:
                        trade = self.execute_buy(
                            symbol=candidate['symbol'],
                            trade_date=trade_date,
                            signal_date=trade_date,
                            price=price,
                            shares=shares,
                            signal_score=candidate['composite_score'],
                            signal_rank=candidate['signal_rank'],
                            composite_score=candidate['composite_score'],
                            atr=atr,
                            industry_name=candidate['industry_name']
                        )
                        
                        if trade:
                            daily_pnl -= trade.total_cost
                
                current_equity = self.capital + sum(p.market_value for p in self.positions.values())
                self.equity_curve.append((trade_date, current_equity))
                self.daily_pnl[trade_date] = daily_pnl
            
            return self.generate_report()
            
        except Exception as e:
            logger.error(f"V58 run_backtest FAILED: {e}")
            logger.error(traceback.format_exc())
            return {'error': str(e)}
    
    def generate_report(self) -> Dict[str, Any]:
        """生成回测报告"""
        total_trades = len([t for t in self.trades if t.side == 'BUY'])
        profitable_trades = len([a for a in self.trade_audit if a.is_profitable])
        
        total_net_pnl = sum(a.net_pnl for a in self.trade_audit)
        total_fees = sum(a.total_fees for a in self.trade_audit)
        
        if self.equity_curve:
            initial_equity = self.equity_curve[0][1]
            final_equity = self.equity_curve[-1][1]
            total_return = (final_equity - initial_equity) / initial_equity
        else:
            total_return = 0.0
            final_equity = self.initial_capital
        
        max_drawdown = self.calculate_max_drawdown()
        
        avg_holding_days = np.mean([a.holding_days for a in self.trade_audit]) if self.trade_audit else 0
        win_rate = profitable_trades / total_trades if total_trades > 0 else 0
        
        avg_win = np.mean([a.net_pnl for a in self.trade_audit if a.is_profitable]) if profitable_trades > 0 else 0
        avg_loss = np.mean([a.net_pnl for a in self.trade_audit if not a.is_profitable]) if (total_trades - profitable_trades) > 0 else 0
        profit_loss_ratio = abs(avg_win / avg_loss) if avg_loss != 0 else 0
        
        return {
            'total_return': total_return,
            'final_equity': final_equity,
            'initial_capital': self.initial_capital,
            'total_trades': total_trades,
            'profitable_trades': profitable_trades,
            'win_rate': win_rate,
            'max_drawdown': max_drawdown,
            'total_net_pnl': total_net_pnl,
            'total_fees': total_fees,
            'avg_holding_days': avg_holding_days,
            'profit_loss_ratio': profit_loss_ratio,
            'total_positions': len(self.positions),
            'wash_sale_prevented': len(self.wash_sale_records),
            'blacklist_count': len(self.blacklist),
            'equity_curve': self.equity_curve,
            'daily_pnl': self.daily_pnl,
            'trade_audit': self.trade_audit,
            'meets_target': total_return >= V58_RETURN_TARGET and max_drawdown <= V58_MDD_TARGET
        }
    
    def calculate_max_drawdown(self) -> float:
        """计算最大回撤"""
        if not self.equity_curve:
            return 0.0
        
        equity_values = [eq for _, eq in self.equity_curve]
        peak = equity_values[0]
        max_dd = 0.0
        
        for eq in equity_values:
            if eq > peak:
                peak = eq
            dd = (peak - eq) / peak if peak > 0 else 0
            max_dd = max(max_dd, dd)
        
        return max_dd
