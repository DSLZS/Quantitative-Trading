# V58 风险管理器 - 三级防御体系
# ===========================================

class V58RiskManager:
    """
    V58 风险管理器 - 三级防御体系
    
    【核心功能】
    1. 硬止损：6% 硬止损 或 2.0*ATR 止损
    2. 保本止损：浮盈超 4% 后激活，成本价 +0.3% 缓冲
    3. 动态止盈：浮盈≥8% 激活追踪止盈，回撤 2.0*ATR
    4. 阶梯止盈：8% 减仓 25%，15% 减仓 35%
    5. 时间止损：5 天后减仓 50%
    6. MA20 趋势离场：跌破 MA20 离场
    """
    
    def __init__(self):
        self.hard_stop_loss_ratio = V58_HARD_STOP_LOSS_RATIO
        self.hard_stop_loss_atr_mult = V58_HARD_STOP_LOSS_ATR_MULT
        self.breakeven_profit_threshold = V58_BREAKEVEN_PROFIT_THRESHOLD
        self.breakeven_buffer = V58_BREAKEVEN_BUFFER
        self.trailing_profit_trigger = V58_TRAILING_PROFIT_TRIGGER
        self.trailing_profit_atr_mult = V58_TRAILING_PROFIT_ATR_MULT
        self.tiered_profit_levels = V58_TIERED_PROFIT_LEVELS
        self.time_stop_days = V58_TIME_STOP_DAYS
        self.time_stop_reduce_ratio = V58_TIME_STOP_REDUCE_RATIO
        self.friction_cost = V58_FRICTION_COST
    
    def check_hard_stop_loss(self, position: V58Position, current_price: float, 
                             current_atr: float) -> Tuple[bool, str]:
        """
        检查硬止损条件
        
        【逻辑】
        1. 固定止损：亏损超过 6%
        2. ATR 止损：亏损超过 2.0 * ATR
        
        返回：(是否触发止损，止损原因)
        """
        cost_price = position.avg_cost
        if cost_price <= 0:
            return False, ""
        
        current_profit_ratio = (current_price - cost_price) / cost_price
        
        # 固定百分比止损
        fixed_stop_price = cost_price * (1 - self.hard_stop_loss_ratio)
        if current_price <= fixed_stop_price:
            position.hard_stop_price = fixed_stop_price
            position.hard_stop_triggered = True
            return True, f"硬止损 (亏损>{self.hard_stop_loss_ratio*100:.1f}%)"
        
        # ATR 止损
        if current_atr > 0 and position.atr_at_entry > 0:
            atr_stop_price = cost_price - (self.hard_stop_loss_atr_mult * current_atr)
            if current_price <= atr_stop_price:
                position.hard_stop_price = atr_stop_price
                position.hard_stop_triggered = True
                return True, f"ATR 止损 (亏损>{self.hard_stop_loss_atr_mult}*ATR)"
        
        return False, ""
    
    def check_breakeven_stop(self, position: V58Position, current_price: float) -> Tuple[bool, str]:
        """
        检查保本止损条件
        
        【逻辑】
        1. 浮盈超过 4% 后激活保本止损
        2. 保本止损价 = 买入成本价 * (1 + 0.3%)，覆盖手续费
        3. 手续费覆盖检查：预期 PnL 扣除 0.2% 摩擦成本后 >= 0
        
        返回：(是否触发，止损原因)
        """
        cost_price = position.avg_cost
        if cost_price <= 0:
            return False, ""
        
        current_profit_ratio = (current_price - cost_price) / cost_price
        
        # 检查是否已激活保本止损
        if not position.breakeven_active:
            if current_profit_ratio >= self.breakeven_profit_threshold:
                position.breakeven_active = True
                # 保本止损价 = 成本价 * (1 + 缓冲), 确保扣除手续费后不亏
                position.breakeven_stop_price = cost_price * (1 + self.breakeven_buffer)
        else:
            # 已激活保本止损，检查是否触发
            if current_price <= position.breakeven_stop_price:
                # 手续费覆盖验证
                expected_net_pnl = (position.breakeven_stop_price - cost_price) / cost_price - self.friction_cost
                if expected_net_pnl >= 0:
                    return True, "保本止损 (手续费覆盖)"
                else:
                    return True, "保本止损 (缓冲保护)"
        
        return False, ""
    
    def check_trailing_profit(self, position: V58Position, current_price: float,
                              current_atr: float) -> Tuple[bool, str]:
        """
        检查动态追踪止盈条件
        
        【逻辑】
        1. 浮盈≥8% 后激活追踪止盈
        2. 追踪止盈价 = 最高价 - 2.0 * ATR
        3. 价格跌破追踪止盈价时触发
        
        返回：(是否触发，止盈原因)
        """
        cost_price = position.avg_cost
        if cost_price <= 0:
            return False, ""
        
        current_profit_ratio = (current_price - cost_price) / cost_price
        
        # 更新最高价
        if current_price > position.peak_price:
            position.peak_price = current_price
            position.peak_profit = (current_price - cost_price) / cost_price
        
        # 检查是否激活追踪止盈
        if not position.trailing_profit_active:
            if current_profit_ratio >= self.trailing_profit_trigger:
                position.trailing_profit_active = True
                if current_atr > 0:
                    position.trailing_profit_stop = current_price - (self.trailing_profit_atr_mult * current_atr)
                else:
                    position.trailing_profit_stop = current_price * (1 - 0.05)  # 默认 5% 回撤
        else:
            # 已激活，检查是否触发
            if position.trailing_profit_stop > 0 and current_price <= position.trailing_profit_stop:
                if not position.trailing_profit_triggered:
                    position.trailing_profit_triggered = True
                    return True, f"追踪止盈 (回撤{self.trailing_profit_atr_mult}*ATR)"
        
        return False, ""
    
    def check_tiered_profit(self, position: V58Position, current_price: float) -> Tuple[bool, float, str]:
        """
        检查阶梯止盈条件
        
        【逻辑】
        1. 浮盈 8% 减仓 25%
        2. 浮盈 15% 减仓 35%
        
        返回：(是否触发减仓，减仓比例，原因)
        """
        if not V58_TIERED_PROFIT_ENABLED:
            return False, 0.0, ""
        
        cost_price = position.avg_cost
        if cost_price <= 0:
            return False, 0.0, ""
        
        current_profit_ratio = (current_price - cost_price) / cost_price
        
        for level in self.tiered_profit_levels:
            threshold = level['threshold']
            reduce_ratio = level['reduce_ratio']
            
            if current_profit_ratio >= threshold:
                level_idx = self.tiered_profit_levels.index(level)
                if level_idx not in position.tiered_profit_triggered:
                    position.tiered_profit_triggered.append(level_idx)
                    return True, reduce_ratio, f"阶梯止盈 (浮盈{threshold*100:.1f}%)"
        
        return False, 0.0, ""
    
    def check_time_stop(self, position: V58Position, current_date: str) -> Tuple[bool, str]:
        """
        检查时间止损条件
        
        【逻辑】
        1. 持仓超过 5 天且浮盈 < 2%，减仓 50%
        
        返回：(是否触发，原因)
        """
        if not V58_TIME_STOP_ENABLED:
            return False, ""
        
        if position.time_stop_triggered:
            return False, ""
        
        try:
            buy_date = datetime.strptime(position.buy_date, "%Y-%m-%d")
            current = datetime.strptime(current_date, "%Y-%m-%d")
            holding_days = (current - buy_date).days
            
            position.holding_days = holding_days
            
            if holding_days >= self.time_stop_days:
                cost_price = position.avg_cost
                current_profit = (current_price - cost_price) / cost_price if cost_price > 0 else 0
                
                if current_profit < 0.02:  # 浮盈小于 2%
                    position.time_stop_triggered = True
                    return True, f"时间止损 (持仓{holding_days}天)"
        except Exception:
            pass
        
        return False, ""
    
    def check_ma20_exit(self, position: V58Position, current_price: float,
                        current_ma20: float) -> Tuple[bool, str]:
        """
        检查 MA20 趋势离场条件
        
        【逻辑】
        1. 收盘价跌破 MA20 且 MA20 向下倾斜
        2. 仅在浮盈 > 0 时触发（避免在亏损时离场）
        
        返回：(是否触发，原因)
        """
        if not V58_MA20_TREND_EXIT_ENABLED:
            return False, ""
        
        if position.ma20_exit_triggered:
            return False, ""
        
        cost_price = position.avg_cost
        if cost_price <= 0:
            return False, ""
        
        current_profit = (current_price - cost_price) / cost_price
        
        # 跌破 MA20 且有浮盈
        if current_price < current_ma20 and current_profit > 0:
            position.ma20_exit_triggered = True
            return True, "MA20 趋势离场"
        
        return False, ""
    
    def update_position_stops(self, position: V58Position, current_price: float,
                              current_atr: float, current_ma20: float):
        """
        更新持仓的止损止盈价格
        
        【功能】
        1. 更新硬止损价
        2. 更新保本止损价（如已激活）
        3. 更新追踪止盈价（如已激活）
        """
        cost_price = position.avg_cost
        if cost_price <= 0:
            return
        
        current_profit_ratio = (current_price - cost_price) / cost_price
        
        # 更新硬止损价
        hard_stop_price = max(
            cost_price * (1 - self.hard_stop_loss_ratio),
            cost_price - (self.hard_stop_loss_atr_mult * current_atr) if current_atr > 0 else 0
        )
        position.hard_stop_price = hard_stop_price
        
        # 更新保本止损价
        if current_profit_ratio >= self.breakeven_profit_threshold:
            position.breakeven_active = True
            position.breakeven_stop_price = cost_price * (1 + self.breakeven_buffer)
        
        # 更新追踪止盈价
        if current_profit_ratio >= self.trailing_profit_trigger:
            position.trailing_profit_active = True
            if current_atr > 0:
                position.trailing_profit_stop = current_price - (self.trailing_profit_atr_mult * current_atr)
    
    def check_all_exits(self, position: V58Position, current_price: float,
                        current_atr: float, current_ma20: float,
                        current_date: str) -> Tuple[bool, str]:
        """
        检查所有离场条件（综合检查）
        
        【优先级】
        1. 硬止损（最高优先级）
        2. 保本止损
        3. 追踪止盈
        4. MA20 趋势离场
        5. 时间止损（最低优先级）
        
        返回：(是否触发离场，离场原因)
        """
        # 1. 硬止损（最高优先级）
        triggered, reason = self.check_hard_stop_loss(position, current_price, current_atr)
        if triggered:
            return True, reason
        
        # 2. 保本止损
        triggered, reason = self.check_breakeven_stop(position, current_price)
        if triggered:
            return True, reason
        
        # 3. 追踪止盈
        triggered, reason = self.check_trailing_profit(position, current_price, current_atr)
        if triggered:
            return True, reason
        
        # 4. MA20 趋势离场
        triggered, reason = self.check_ma20_exit(position, current_price, current_ma20)
        if triggered:
            return True, reason
        
        # 5. 时间止损
        triggered, reason = self.check_time_stop(position, current_date)
        if triggered:
            return True, reason
        
        return False, ""
    
    def calculate_position_size(self, capital: float, current_price: float,
                                atr: float, volatility: float) -> int:
        """
        计算头寸大小（波动率适配）
        
        【逻辑】
        1. 每仓风险 = 总资本 * 0.8%
        2. 头寸大小 = 每仓风险 / (ATR * 2)
        3. 单仓上限 = 总资本 * 18% / 当前价
        """
        risk_per_position = capital * V58_RISK_TARGET_PER_POSITION
        
        if atr > 0:
            risk_shares = int(risk_per_position / (atr * 2))
        else:
            risk_shares = int(risk_per_position / (current_price * 0.05))
        
        max_position_value = capital * V58_MAX_SINGLE_POSITION_PCT
        max_shares = int(max_position_value / current_price)
        
        shares = min(risk_shares, max_shares)
        
        if shares > 0:
            shares = max(shares, 100)
            shares = (shares // 100) * 100
        
        return shares


