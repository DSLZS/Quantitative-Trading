# V59 风险管理器 - 动态止损与利润生长空间
# ===========================================

class V59RiskManager:
    """
    V59 风险管理器 - 动态止损与利润生长空间
    
    【核心功能 - V59 改进】
    1. 硬止损：废除 8% 固定止损，完全依赖 ATR 动态止损（3.0 * ATR）
    2. 保本止损：浮盈必须 >= 10% 才能激活（从 4% 提高）
    3. 动态止盈：浮盈必须 >= 15% 才能激活追踪止盈（从 8% 提高）
    4. 追踪止盈：回撤 3.0 * ATR（从 2.0 提高）
    5. 阶梯止盈：只在浮盈 >= 15% 后启动
    6. 时间止损：8 天后减仓（从 5 天延长）
    7. MA20 趋势离场：跌破 MA20 离场
    """
    
    def __init__(self):
        # V59: 完全依赖 ATR 止损，废除固定百分比止损
        self.hard_stop_loss_atr_mult = V59_HARD_STOP_LOSS_ATR_MULT  # 3.0
        self.hard_stop_loss_mode = V59_HARD_STOP_LOSS_MODE  # "atr_only"
        
        # V59: 浮盈必须 >= 10% 才能激活保本止损
        self.breakeven_profit_threshold = V59_BREAKEVEN_PROFIT_THRESHOLD  # 0.10
        self.breakeven_buffer = V59_BREAKEVEN_BUFFER  # 0.003
        
        # V59: 浮盈必须 >= 15% 才能激活追踪止盈
        self.trailing_profit_trigger = V59_TRAILING_PROFIT_TRIGGER  # 0.15
        self.trailing_profit_atr_mult = V59_TRAILING_PROFIT_ATR_MULT  # 3.0
        
        # V59: 阶梯止盈阈值提高
        self.tiered_profit_levels = V59_TIERED_PROFIT_LEVELS
        
        # V59: 时间止损延长到 8 天
        self.time_stop_days = V59_TIME_STOP_DAYS
        self.time_stop_reduce_ratio = V59_TIME_STOP_REDUCE_RATIO
        
        self.friction_cost = V59_FRICTION_COST
    
    def check_hard_stop_loss(self, position: V59Position, current_price: float, 
                             current_atr: float) -> Tuple[bool, str]:
        """
        检查硬止损条件 - V59: 完全依赖 ATR，废除固定百分比止损
        
        【逻辑】
        1. ATR 止损：亏损超过 3.0 * ATR（基于入场 ATR）
        
        返回：(是否触发止损，止损原因)
        """
        cost_price = position.avg_cost
        if cost_price <= 0:
            return False, ""
        
        # V59: 只使用 ATR 止损，不再使用固定百分比止损
        if current_atr > 0 and position.atr_at_entry > 0:
            # 使用入场时的 ATR 和当前 ATR 的较大值
            effective_atr = max(current_atr, position.atr_at_entry)
            atr_stop_price = cost_price - (self.hard_stop_loss_atr_mult * effective_atr)
            
            if current_price <= atr_stop_price:
                position.hard_stop_price = atr_stop_price
                position.hard_stop_triggered = True
                return True, f"ATR 止损 (亏损>{self.hard_stop_loss_atr_mult}*ATR={effective_atr:.2f})"
        
        return False, ""
    
    def check_breakeven_stop(self, position: V59Position, current_price: float) -> Tuple[bool, str]:
        """
        检查保本止损条件 - V59: 浮盈必须 >= 10% 才能激活
        
        【逻辑】
        1. 浮盈超过 10% 后激活保本止损
        2. 保本止损价 = 买入成本价 * (1 + 0.3%)，覆盖手续费
        3. 手续费覆盖检查：预期 PnL 扣除 0.2% 摩擦成本后 >= 0
        
        返回：(是否触发，止损原因)
        """
        cost_price = position.avg_cost
        if cost_price <= 0:
            return False, ""
        
        current_profit_ratio = (current_price - cost_price) / cost_price
        
        # V59: 检查是否已激活保本止损 - 浮盈必须 >= 10%
        if not position.breakeven_active:
            if current_profit_ratio >= self.breakeven_profit_threshold:
                position.breakeven_active = True
                # 保本止损价 = 成本价 * (1 + 缓冲), 确保扣除手续费后不亏
                position.breakeven_stop_price = cost_price * (1 + self.breakeven_buffer)
        else:
            # 已激活保本止损，检查是否触发
            if current_price <= position.breakeven_stop_price:
                # 手续费覆盖验证
                expected_net_pnl = (position.breakeven_stop_price - cost_price) / cost_price - self.friction_cost
                if expected_net_pnl >= 0:
                    return True, "保本止损 (手续费覆盖)"
                else:
                    return True, "保本止损 (缓冲保护)"
        
        return False, ""
    
    def check_trailing_profit(self, position: V59Position, current_price: float,
                              current_atr: float) -> Tuple[bool, str]:
        """
        检查动态追踪止盈条件 - V59: 浮盈必须 >= 15% 才能激活
        
        【逻辑】
        1. 浮盈≥15% 后激活追踪止盈
        2. 追踪止盈价 = 最高价 - 3.0 * ATR
        3. 价格跌破追踪止盈价时触发
        
        返回：(是否触发，止盈原因)
        """
        cost_price = position.avg_cost
        if cost_price <= 0:
            return False, ""
        
        current_profit_ratio = (current_price - cost_price) / cost_price
        
        # 更新最高价
        if current_price > position.peak_price:
            position.peak_price = current_price
            position.peak_profit = (current_price - cost_price) / cost_price
        
        # V59: 检查是否激活追踪止盈 - 浮盈必须 >= 15%
        if not position.trailing_profit_active:
            if current_profit_ratio >= self.trailing_profit_trigger:
                position.trailing_profit_active = True
                if current_atr > 0:
                    position.trailing_profit_stop = current_price - (self.trailing_profit_atr_mult * current_atr)
                else:
                    position.trailing_profit_stop = current_price * (1 - 0.08)  # 默认 8% 回撤
        else:
            # 已激活，检查是否触发
            if position.trailing_profit_stop > 0 and current_price <= position.trailing_profit_stop:
                if not position.trailing_profit_triggered:
                    position.trailing_profit_triggered = True
                    return True, f"追踪止盈 (回撤{self.trailing_profit_atr_mult}*ATR)"
        
        return False, ""
    
    def check_tiered_profit(self, position: V59Position, current_price: float) -> Tuple[bool, float, str]:
        """
        检查阶梯止盈条件 - V59: 只在浮盈 >= 15% 后启动
        
        【逻辑】
        1. 浮盈 15% 减仓 25%
        2. 浮盈 25% 减仓 35%
        
        返回：(是否触发减仓，减仓比例，原因)
        """
        if not V59_TIERED_PROFIT_ENABLED:
            return False, 0.0, ""
        
        cost_price = position.avg_cost
        if cost_price <= 0:
            return False, 0.0, ""
        
        current_profit_ratio = (current_price - cost_price) / cost_price
        
        for level in self.tiered_profit_levels:
            threshold = level['threshold']
            reduce_ratio = level['reduce_ratio']
            
            if current_profit_ratio >= threshold:
                level_idx = self.tiered_profit_levels.index(level)
                if level_idx not in position.tiered_profit_triggered:
                    position.tiered_profit_triggered.append(level_idx)
                    return True, reduce_ratio, f"阶梯止盈 (浮盈{threshold*100:.1f}%)"
        
        return False, 0.0, ""
    
    def check_time_stop(self, position: V59Position, current_date: str, current_price: float) -> Tuple[bool, str]:
        """
        检查时间止损条件 - V59: 8 天后减仓
        
        【逻辑】
        1. 持仓超过 8 天且浮盈 < 2%，减仓 50%
        
        返回：(是否触发，原因)
        """
        if not V59_TIME_STOP_ENABLED:
            return False, ""
        
        if position.time_stop_triggered:
            return False, ""
        
        try:
            buy_date = datetime.strptime(position.buy_date, "%Y-%m-%d")
            current = datetime.strptime(current_date, "%Y-%m-%d")
            holding_days = (current - buy_date).days
            
            position.holding_days = holding_days
            
            if holding_days >= self.time_stop_days:
                cost_price = position.avg_cost
                current_profit = (current_price - cost_price) / cost_price if cost_price > 0 else 0
                
                if current_profit < 0.02:  # 浮盈小于 2%
                    position.time_stop_triggered = True
                    return True, f"时间止损 (持仓{holding_days}天)"
        except Exception:
            pass
        
        return False, ""
    
    def check_ma20_exit(self, position: V59Position, current_price: float,
                        current_ma20: float) -> Tuple[bool, str]:
        """
        检查 MA20 趋势离场条件
        
        【逻辑】
        1. 收盘价跌破 MA20 且 MA20 向下倾斜
        2. 仅在浮盈 > 0 时触发（避免在亏损时离场）
        
        返回：(是否触发，原因)
        """
        if not V59_MA20_TREND_EXIT_ENABLED:
            return False, ""
        
        if position.ma20_exit_triggered:
            return False, ""
        
        cost_price = position.avg_cost
        if cost_price <= 0:
            return False, ""
        
        current_profit = (current_price - cost_price) / cost_price
        
        # 跌破 MA20 且有浮盈
        if current_price < current_ma20 and current_profit > 0:
            position.ma20_exit_triggered = True
            return True, "MA20 趋势离场"
        
        return False, ""
    
    def update_position_stops(self, position: V59Position, current_price: float,
                              current_atr: float, current_ma20: float):
        """
        更新持仓的止损止盈价格
        
        【功能】
        1. 更新 ATR 硬止损价
        2. 更新保本止损价（如已激活）
        3. 更新追踪止盈价（如已激活）
        """
        cost_price = position.avg_cost
        if cost_price <= 0:
            return
        
        current_profit_ratio = (current_price - cost_price) / cost_price
        
        # V59: 更新 ATR 硬止损价（不再使用固定百分比）
        if current_atr > 0:
            effective_atr = max(current_atr, position.atr_at_entry)
            hard_stop_price = cost_price - (self.hard_stop_loss_atr_mult * effective_atr)
            position.hard_stop_price = hard_stop_price
        
        # 更新保本止损价
        if current_profit_ratio >= self.breakeven_profit_threshold:
            position.breakeven_active = True
            position.breakeven_stop_price = cost_price * (1 + self.breakeven_buffer)
        
        # 更新追踪止盈价
        if current_profit_ratio >= self.trailing_profit_trigger:
            position.trailing_profit_active = True
            if current_atr > 0:
                position.trailing_profit_stop = current_price - (self.trailing_profit_atr_mult * current_atr)
    
    def check_all_exits(self, position: V59Position, current_price: float,
                        current_atr: float, current_ma20: float,
                        current_date: str) -> Tuple[bool, str]:
        """
        检查所有离场条件（综合检查）
        
        【优先级】
        1. 硬止损（最高优先级）
        2. 保本止损
        3. 追踪止盈
        4. MA20 趋势离场
        5. 时间止损（最低优先级）
        
        返回：(是否触发离场，离场原因)
        """
        # 1. 硬止损（最高优先级）
        triggered, reason = self.check_hard_stop_loss(position, current_price, current_atr)
        if triggered:
            return True, reason
        
        # 2. 保本止损
        triggered, reason = self.check_breakeven_stop(position, current_price)
        if triggered:
            return True, reason
        
        # 3. 追踪止盈
        triggered, reason = self.check_trailing_profit(position, current_price, current_atr)
        if triggered:
            return True, reason
        
        # 4. MA20 趋势离场
        triggered, reason = self.check_ma20_exit(position, current_price, current_ma20)
        if triggered:
            return True, reason
        
        # 5. 时间止损
        triggered, reason = self.check_time_stop(position, current_date, current_price)
        if triggered:
            return True, reason
        
        return False, ""
    
    def calculate_position_size(self, capital: float, current_price: float,
                                atr: float, volatility: float) -> int:
        """
        计算头寸大小 - V59: 波动率适配
        
        【逻辑】
        1. 每仓风险 = 总资本 * 1.0%
        2. 头寸大小 = 每仓风险 / (ATR * 2)
        3. 单仓上限 = 总资本 * 20% / 当前价
        """
        risk_per_position = capital * V59_RISK_TARGET_PER_POSITION
        
        if atr > 0:
            risk_shares = int(risk_per_position / (atr * 2))
        else:
            risk_shares = int(risk_per_position / (current_price * 0.05))
        
        max_position_value = capital * V59_MAX_SINGLE_POSITION_PCT
        max_shares = int(max_position_value / current_price)
        
        shares = min(risk_shares, max_shares)
        
        if shares > 0:
            shares = max(shares, 100)
            shares = (shares // 100) * 100
        
        return shares
